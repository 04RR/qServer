"""Discriminating quality probe: does IQ3_S preserve the 122B's edge over the 35B?

DESIGN PRINCIPLE: the only meaningful signal is the 122B winning where the 35B loses.
  - too easy  -> both pass -> no signal (the M2 failure: 24/24 vs 24/24)
  - too hard  -> both fail -> no signal
  - in the gap-> 35B fails, healthy 122B passes. Only here can IQ3 damage show, as the 122B
                 failing to win and scoring toward the 35B instead of above it.
So the 35B is the CALIBRATION INSTRUMENT, not a sideshow: any item it aces is DISCARDED (it
didn't probe the gap). We filter empirically rather than hoping the items are hard enough.

GROUND TRUTH IS COMPUTED, NOT HAND-WRITTEN. Every item is generated by code that also solves it
(brute force / direct execution), so difficulty can be tuned freely without me becoming the error
source. A wrong answer key fails a correct model and would silently poison the verdict.

Usage:
  probe_discriminating.py gen                          -> write items.json (candidate pool)
  probe_discriminating.py run <url> <model> <tag> [n] [a:b]  -> score, append to scores_<tag>.jsonl
  probe_discriminating.py calibrate <tag>              -> keep only items the 35B failed -> gap.json
  probe_discriminating.py report                       -> 3-way table + verdict
"""
