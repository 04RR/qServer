# ---------------------------------------------------------------- item generators
def gen_chain(rng, n_steps):
    """Long dependent arithmetic chain: one early slip propagates to a wrong final answer."""
    x = rng.randint(3, 19)
    desc = [f"Start with {x}."]
    for _ in range(n_steps):
        op = rng.choice(["mul", "add", "sub", "sq", "half"])
        if op == "mul":
            k = rng.randint(2, 7); x *= k; desc.append(f"Multiply by {k}.")
        elif op == "add":
            k = rng.randint(3, 40); x += k; desc.append(f"Add {k}.")
        elif op == "sub":
            k = rng.randint(3, 40); x -= k; desc.append(f"Subtract {k}.")
        elif op == "sq":
            if abs(x) > 60: continue
            x = x * x; desc.append("Square the result.")
        else:
            if x % 2 != 0: x += 1; desc.append("Add 1.")
            x //= 2; desc.append("Divide by 2.")
    prompt = " ".join(desc) + " Give ONLY the final integer, nothing else."
    return prompt, str(x)

def gen_trace(rng):
    """Code trace with state a smaller model tends to lose. Ground truth = actual execution."""
    a, b, c = rng.randint(2, 5), rng.randint(2, 6), rng.randint(7, 15)
    src = (
        "def f(n):\n"
        "    t, s = 0, []\n"
        "    for i in range(1, n + 1):\n"
        f"        if i % {a} == 0:\n"
        "            t += i * 2\n"
        "            s.append(i)\n"
        f"        elif i % {b} == 0:\n"
        "            t -= i\n"
        "            if s: t += s.pop()\n"
        "        else:\n"
        "            t += 1\n"
        f"    return t + len(s)\n\nprint(f({c}))"
    )
    ns = {}
    exec(src.replace(f"print(f({c}))", ""), ns)
    val = ns["f"](c)
    prompt = ("Trace this Python code exactly, step by step, and give ONLY the printed integer:\n\n"
              + src)
    return prompt, str(val)

def gen_schedule(rng, n):
    """Constraint satisfaction with a UNIQUE brute-forced solution.
    The 2-bit gate/up failure mode is dropping a constraint mid-solve -> high value."""
    people = ["Ana", "Ben", "Cara", "Dan", "Eli", "Fay"][:n]
    for _ in range(400):
        sol = list(range(n)); rng.shuffle(sol)
        pos = {p: sol[i] for i, p in enumerate(people)}
        cons, texts = [], []
        pairs = list(itertools.combinations(people, 2)); rng.shuffle(pairs)
        for (p, q) in pairs[:n]:
            if pos[p] < pos[q]:
                cons.append(lambda a, p=p, q=q: a[p] < a[q]); texts.append(f"{p} is scheduled before {q}.")
            else:
                cons.append(lambda a, p=p, q=q: a[q] < a[p]); texts.append(f"{q} is scheduled before {p}.")
        p0 = rng.choice(people)
        cons.append(lambda a, p0=p0, v=pos[p0]: a[p0] == v)
        texts.append(f"{p0} is in slot {pos[p0]+1}.")
        for (p, q) in pairs[n:n+2]:
            if abs(pos[p]-pos[q]) != 1:
                cons.append(lambda a, p=p, q=q: abs(a[p]-a[q]) != 1)
                texts.append(f"{p} and {q} are NOT in adjacent slots.")
        sols = []
        for perm in itertools.permutations(range(n)):
            a = {p: perm[i] for i, p in enumerate(people)}
            if all(c(a) for c in cons): sols.append(a)
            if len(sols) > 1: break
        if len(sols) == 1:
            rng.shuffle(texts)
            prompt = (f"{n} people are each assigned exactly one of slots 1..{n} (one person per slot).\n"
                      + "\n".join("- " + t for t in texts)
                      + f"\n\nThere is exactly one valid assignment. Give ONLY the slot number (1..{n}) "
                        f"for {people[0]}, as a single integer.")
            return prompt, str(sols[0][people[0]] + 1)
    return None

def gen_compose(rng, k):
    """Nested/conditional rules over a list; a smaller model collapses a branch."""
    nums = [rng.randint(2, 60) for _ in range(k)]
    def isprime(v):
        if v < 2: return False
        for d in range(2, int(v**0.5)+1):
            if v % d == 0: return False
        return True
    tot = 0
    for v in nums:
        if v > 30:
            if v % 2 == 0: tot += v // 2
            elif isprime(v): tot -= 3
            else: tot += 1
        else:
            if isprime(v): tot += v * 2
            elif v % 3 == 0: tot -= v
            else: tot += 0
    prompt = ("Apply these rules to each number in the list, in order, and sum the contributions.\n"
              "For each number v:\n"
              "  - If v > 30:\n"
              "      * if v is even, contribute v/2 (integer division)\n"
              "      * else if v is prime, contribute -3\n"
              "      * else contribute +1\n"
              "  - Otherwise (v <= 30):\n"
              "      * if v is prime, contribute v*2\n"
              "      * else if v is divisible by 3, contribute -v\n"
              "      * else contribute 0\n"
              f"\nList: {nums}\n\nGive ONLY the final total as a single integer.")
    return prompt, str(tot)

def gen_needle2(rng, n_sent):
    """Two separated facts that must be COMBINED. Single-needle passes on both models already."""
    a = rng.randint(100, 999); b = rng.randint(100, 999)
    f1 = f"The alpha register holds the value {a}."
    f2 = f"The beta register holds the value {b}."
    filler = [f"Log entry {i}: routine telemetry sample, nominal, no action required." for i in range(1, n_sent)]
    q = int(a) * 2 + int(b)
    i1, i2 = n_sent // 5, (4 * n_sent) // 5
    filler.insert(i1, f1); filler.insert(i2, f2)
    prompt = (" ".join(filler) +
              "\n\nQuestion: compute (alpha register value * 2) + (beta register value). "
              "Both values appear somewhere above. Give ONLY the final integer.")
    return prompt, str(q)

def gen_trace_hard(rng):
    """Nested loops + dict/list state mutation. Ground truth = actual execution."""
    a, b, c = rng.randint(2, 4), rng.randint(3, 5), rng.randint(9, 13)
    src = (
        "def f(n):\n"
        "    d, stack, t = {}, [], 0\n"
        "    for i in range(1, n + 1):\n"
        "        for j in range(1, i + 1):\n"
        f"            k = (i * j) % {a+3}\n"
        "            d[k] = d.get(k, 0) + j\n"
        f"            if j % {a} == 0:\n"
        "                stack.append(i - j)\n"
        f"            elif j % {b} == 0 and stack:\n"
        "                t += stack.pop()\n"
        "        if i % 2 == 0 and d:\n"
        "            t -= min(d.values())\n"
        "    return t + sum(d.values()) - len(stack)\n"
        f"\nprint(f({c}))"
    )
    ns = {}
    exec(src.replace(f"print(f({c}))", ""), ns)
    return ("Trace this Python code exactly and give ONLY the printed integer:\n\n" + src), str(ns["f"](c))

def gen_needle3(rng, n_sent):
    """THREE separated facts that must all be combined. Two-fact passed on both models."""
    a, b, c = rng.randint(100, 999), rng.randint(10, 99), rng.randint(2, 9)
    facts = [f"The alpha register holds the value {a}.",
             f"The beta register holds the value {b}.",
             f"The gamma coefficient is {c}."]
    filler = [f"Log entry {i}: routine telemetry sample, nominal, no action required." for i in range(1, n_sent)]
    for pos, fct in zip((n_sent // 7, (3 * n_sent) // 7, (6 * n_sent) // 7), facts):
        filler.insert(pos, fct)
    val = (a - b) * c
    prompt = (" ".join(filler) +
              "\n\nQuestion: compute (alpha register value - beta register value) * gamma coefficient. "
              "All three values appear somewhere above. Give ONLY the final integer.")
    return prompt, str(val)

