# ---------------------------------------------------------------- scoring
def check(ans, text):
    """Strict: the ground-truth integer must appear as the last integer in the reply."""
    nums = re.findall(r"-?\d+", text.replace(",", ""))
    return bool(nums) and nums[-1] == str(ans)

def ask(base, model, prompt, temp=0.6):
    body = json.dumps({"model": model,
                       "messages": [{"role": "system", "content": SYS}, {"role": "user", "content": prompt}],
                       # per-model floor from M2's 'empty answer' FAIL: this model thinks LONG.
                       # a truncated chain scores wrong for the wrong reason and poisons the result.
                       "max_tokens": 16000,
                       "temperature": temp, "top_p": 0.95, "top_k": 20, "stream": False}).encode()
    r = urllib.request.Request(base + "/v1/chat/completions", data=body,
                               headers={"Content-Type": "application/json"})
    d = json.load(urllib.request.urlopen(r, timeout=1800))
    ch = d["choices"][0]
    return (ch["message"].get("content") or ""), ch.get("finish_reason")

def cmd_run(base, model, tag, n, sl):
    items = json.load(open(SCR / "items.json"))
    # Only score-runs filter to the gap-set. Calibration runs (tag starts with "calib") must see
    # the FULL pool -- filtering them by a previous, possibly EMPTY gap.json silently runs zero
    # items and prints nothing, which looks like success.
    if pathlib.Path(SCR / "gap.json").exists() and not tag.startswith("calib"):
        keep = set(json.load(open(SCR / "gap.json")))
        items = [i for i in items if i["id"] in keep]
    if sl:
        a, b = sl.split(":"); items = items[int(a):int(b)]
    out = open(SCR / f"scores_{tag}.jsonl", "a")
    for it in items:
        res, trunc = [], 0
        for _ in range(n):
            try:
                c, fin = ask(base, model, it["prompt"])
            except Exception as e:
                res.append(None); print(f"  {it['id']:<12} ERR {type(e).__name__}"); continue
            if fin == "length": trunc += 1
            res.append(bool(check(it["ans"], c)))
        hits = sum(1 for x in res if x)
        print(f"  {it['id']:<12} {hits}/{len(res)}  ans={it['ans']:<8} trunc={trunc}")
        out.write(json.dumps({"id": it["id"], "cat": it["cat"], "ans": it["ans"],
                              "res": res, "hits": hits, "n": len(res), "trunc": trunc}) + "\n")
        out.flush()

def cmd_calibrate(tag):
    rows = [json.loads(l) for l in open(SCR / f"scores_{tag}.jsonl")]
    best = {}
    for r in rows: best[r["id"]] = r          # last wins
    gap = [r["id"] for r in best.values() if r["hits"] < r["n"]]   # 35B failed or was inconsistent
    aced = [r["id"] for r in best.values() if r["hits"] == r["n"]]
    json.dump(gap, open(SCR / "gap.json", "w"))
    print(f"  candidates : {len(best)}")
    print(f"  35B ACED   : {len(aced)}  -> DISCARDED (not in the gap, would prove nothing)")
    print(f"  35B FAILED : {len(gap)}  -> the gap-set")
    bycat = collections.Counter(best[i]["cat"] for i in gap)
    print(f"  gap-set by category: {dict(bycat)}")
    if len(gap) < 10:
        print("\n  !! FEWER THAN 10 GAP ITEMS. The 35B is not failing enough to calibrate against.")
        print("     That is itself a finding — see the 'honest failure mode' in the brief.")
    return gap

